HEADER = """\
<!-- Generated by scripts/generate_api.py. Do not edit by hand. -->

# TASI API overview

Compact list of the public classes and functions of `tasi`, generated from the
code. Full documentation: https://tasi.readthedocs.io (or `help(obj)`).

## Concepts

- **Tabular core:** `Pose`, `Trajectory` and the `Dataset` classes are `pandas.DataFrame`
  subclasses with a `(timestamp, id)` row index and multi-level columns such as
  `("position", "easting")` or `("boundingbox", "center", "northing")`. Positions are UTM
  coordinates. All pandas methods work on them.
- **Hierarchy:** a `TrajectoryDataset` contains many traffic participants,
  `TrajectoryDataset.trajectory(id)` returns one `Trajectory`, and a `Trajectory` consists of
  `Pose` rows. The `Geo*` variants are `geopandas` based and add shapely geometries.
- **Public models (`tasi.io`):** pydantic models (`PosePublic`, `TrajectoryPublic`, ...) to
  exchange data, e.g. `TrajectoryPublic.from_tasi(trajectory)` and back with `.as_tasi()`.
- **ORM (`tasi.io.orm`):** SQLAlchemy models of the same entities. Tables use the placeholder
  schema `schema`, which only resolves through an engine from
  `DatabaseSettings().create_engine()` (settings from `TASI_ORM_*` variables or `.tasiorm`).
- **Safety metrics:** `trajectory.smos.pet(other)` returns a `tasi.smos.PET`.

## Extras

The base package only needs `numpy` and `pandas`. Modules that need an extra raise an
`ImportError` naming it.

| Extra | Enables |
|---|---|
| `geo` | `Geo*` classes (geopandas, shapely) |
| `io` | `tasi.io`, `tasi.io.orm`, `tasi.smos` (pydantic, SQLAlchemy) |
| `database` | PostgreSQL driver (psycopg) for `tasi.io.orm` |
| `visualization` | `tasi.plotting` (matplotlib) |
| `wms` | `tasi.plotting.wms` (map tiles) |
| `performance` | numba in `tasi.calculus` |
| `dtw` | `TrafficLightDataset.synchronize` (dtaidistance) |
| `download` | `tasi.dlr` |
| `osi` | `tasi.io.osi` |
| `all` | everything |

Signatures below omit `self`. Members marked *(property)* are attributes.
"""

_ADDRESS = re.compile(r" at 0x[0-9a-f]+")
# SQLAlchemy internals present on every ORM class
_SKIPPED_ATTRIBUTES = {"metadata", "registry"}
_DOC_LIMIT = 220


# Base classes documented once in ``tasi.base`` instead of under every subclass.
COMMON_BASES = [
    "tasi.base.CollectionBase",
    "tasi.base.PoseCollectionBase",
    "tasi.io.public.base.DataFrameConversionMixin",
]


def summary(obj: Any) -> str:
    """First paragraph of the own docstring of ``obj`` as a single line (not inherited)."""
    doc = obj.__dict__.get("__doc__") if inspect.isclass(obj) else getattr(obj, "__doc__", None)
    if not isinstance(doc, str) or not doc.strip():
        return ""
    doc = inspect.cleandoc(doc)
    if not doc:
        return ""
    first = doc.strip().split("\n\n")[0]
    line = " ".join(part.strip() for part in first.splitlines())
    if len(line) > _DOC_LIMIT:
        line = line[: _DOC_LIMIT - 3].rstrip() + "..."
    return line


def signature(func: Any, drop_first: bool = False) -> str:
    try:
        sig = inspect.signature(func)
    except (TypeError, ValueError):
        return "(...)"
    params = list(sig.parameters.values())
    if drop_first and params:
        params = params[1:]
    text = str(sig.replace(parameters=params))
    return clean_types(_ADDRESS.sub("", text))


def clean_types(text: str) -> str:
    """Make type and default representations short and independent of the installation."""
    import tasi

    text = text.replace(str(Path(tasi.__file__).parent), "<site-packages>/tasi")
    # private module paths differ between versions, e.g. pathlib._local.Path -> pathlib.Path
    text = re.sub(r"\b([a-z]\w*)(?:\.\w+)*\._\w+(?:\.\w+)*\.([A-Z]\w*)", r"\1.\2", text)
    text = re.sub(r"\btasi(?:\.\w+)*\.(\w+)", r"\1", text)
    text = text.replace("<built-in function callable>", "Callable")
    text = re.sub(r"Annotated\[(\w+), FieldInfo\(annotation=.*?\]\)\]", r"\1", text)
    return text.replace("typing.", "").replace("NoneType", "None")


def own_module(obj: Any) -> str:
    return getattr(obj, "__module__", "") or ""


def is_tasi(obj: Any) -> bool:
    return own_module(obj).split(".")[0] == "tasi"


def public_names(module: Any) -> list[str]:
    names = getattr(module, "__all__", None)
    if names is None:
        names = [
            name
            for name, obj in vars(module).items()
            if not name.startswith("_")
            and (inspect.isclass(obj) or inspect.isfunction(obj))
            and own_module(obj).startswith(module.__name__)
        ]
    return sorted(dict.fromkeys(names), key=str.lower)


def fmt(text: str) -> str:
    return f" — {text}" if text else ""


def class_members(cls: type, documented: set[type]) -> Iterator[str]:
    """Public members defined in TASI classes of the MRO of ``cls``.

    Members of bases in ``documented`` are referenced instead of repeated.
    """
    seen: set[str] = set()
    covered: set[type] = set()
    references: list[type] = []
    for base in cls.__mro__[1:]:
        if base in documented and base not in covered:
            references.append(base)
            covered.update(base.__mro__)
    references = [ref for ref in references if not any(ref in o.__mro__[1:] for o in references)]
    fields: dict[str, Any] = getattr(cls, "model_fields", {}) if is_pydantic(cls) else {}

    for name, info in fields.items():
        seen.add(name)
        annotation = getattr(info, "annotation", None)
        type_name = annotation_name(annotation)
        yield f"- `{name}: {type_name}`{fmt(getattr(info, 'description', None) or '')}"

    attributes: list[str] = []
    for klass in cls.__mro__:
        if not is_tasi(klass) or klass in covered:
            continue
        for name, raw in vars(klass).items():
            if name.startswith("_") or name in seen or name in _SKIPPED_ATTRIBUTES:
                continue
            if name in {"model_config", "model_fields", "model_computed_fields"}:
                continue
            seen.add(name)
            if isinstance(raw, property):
                yield f"- `{name}` *(property)*{fmt(summary(raw))}"
            elif isinstance(raw, (classmethod, staticmethod)):
                func = raw.__func__
                kind = "classmethod" if isinstance(raw, classmethod) else "staticmethod"
                sig = signature(func, drop_first=kind == "classmethod")
                yield f"- `{name}{sig}` *({kind})*{fmt(summary(func))}"
            elif inspect.isfunction(raw):
                yield f"- `{name}{signature(raw, drop_first=True)}`{fmt(summary(raw))}"
            elif isinstance(raw, enum.Enum) or callable(raw) or inspect.isclass(raw):
                continue
            else:
                attributes.append(name)
    if attributes:
        yield "- Attributes: " + ", ".join(f"`{name}`" for name in sorted(attributes))
    if references:
        yield "- Inherits the members of " + ", ".join(f"`{ref.__name__}`" for ref in references)


def is_pydantic(cls: type) -> bool:
    return any(
        klass.__module__.startswith("pydantic") and klass.__name__ == "BaseModel"
        for klass in cls.__mro__
    )


def annotation_name(annotation: Any) -> str:
    if annotation is None:
        return "Any"
    if inspect.isclass(annotation) and not getattr(annotation, "__args__", None):
        return annotation.__name__
    text = repr(annotation)
    text = re.sub(r"<class '(?:[\w.]+\.)?(\w+)'>", r"\1", text)
    text = re.sub(r"\b(?:[a-z_][\w]*\.)+([A-Z]\w*)", r"\1", text)
    return clean_types(text)


def base_names(cls: type) -> str:
    bases = [
        base.__qualname__ if is_tasi(base) else f"{base.__module__.split('.')[0]}.{base.__name__}"
        for base in cls.__bases__
        if base is not object
    ]
    return f"({', '.join(bases)})" if bases else ""


def document(name: str, obj: Any, documented: set[type]) -> list[str]:
    if inspect.isclass(obj) and issubclass(obj, enum.Enum):
        values = ", ".join(f"`{member.name}`" for member in obj)
        return [f"### `{name}` (enum)", "", *([summary(obj), ""] if summary(obj) else []), values, ""]
    if inspect.isclass(obj):
        lines = [f"### `class {name}{base_names(obj)}`", ""]
        if summary(obj):
            lines += [summary(obj), ""]
        init = vars(obj).get("__init__")
        if inspect.isfunction(init):
            lines += [f"- `{name}{signature(init, drop_first=True)}`"]
        lines += list(class_members(obj, documented))
        return [*lines, ""]
    if callable(obj):
        return [f"### `{name}{signature(obj)}`", "", *([summary(obj), ""] if summary(obj) else [])]
    value = repr(obj)
    if "/" in value or "\\" in value or len(value) > 80:
        value = type(obj).__name__
    return [f"### `{name}`", "", f"Constant: `{value}`", ""]


def resolve(path: str) -> Any:
    module, name = path.rsplit(".", 1)
    return getattr(importlib.import_module(module), name)


def render() -> str:
    entries: dict[str, list[tuple[str, Any]]] = {}
    for section in SECTIONS:
        if section.module == "tasi.base":
            entries[section.module] = [(path.rsplit(".", 1)[1], resolve(path)) for path in COMMON_BASES]
        else:
            module = importlib.import_module(section.module)
            entries[section.module] = [(name, getattr(module, name)) for name in public_names(module)]
    documented = {obj for items in entries.values() for _, obj in items if inspect.isclass(obj)}

    lines = [HEADER]
    for section in SECTIONS:
        extra = f" — extra `{section.extra}`" if section.extra else ""
        lines += [f"## `{section.module}`{extra}", "", section.description, ""]
        for name, obj in entries[section.module]:
            lines += document(name, obj, documented)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if API.md is outdated")
    args = parser.parse_args()

    content = render()
    if args.check:
        if OUTPUT.read_text() != content:
            print(f"{OUTPUT} is outdated, run: uv run --all-extras python scripts/generate_api.py")
            return 1
        return 0
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
