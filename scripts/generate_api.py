"""Generate ``src/tasi/API.md``, a compact overview of the public API of TASI.

The file is shipped inside the wheel so that tools and coding agents working in
projects that depend on ``tasi`` find all public classes and functions in one
place, e.g. in ``.venv/lib/python3.*/site-packages/tasi/API.md``.

Run with all extras installed::

    uv run --all-extras python scripts/generate_api.py          # write the file
    uv run --all-extras python scripts/generate_api.py --check  # fail if outdated

The test ``src/tests/test_api_reference.py`` runs the check in CI.
"""

